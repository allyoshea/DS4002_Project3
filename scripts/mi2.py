# Load metadata
df = pd.read_csv("marine_species_master_metadata.csv")

# Download images
session = requests.Session()

successful = 0
failed = []

for index, row in df.iterrows():

    category = row["category"]
    split = row["split"]
    obs_id = row["observation_id"]
    image_url = row["image_url"]

    folder = os.path.join(BASE_DIR, split, category)
    image_path = os.path.join(folder, f"{obs_id}.jpg")

    # Skip images already downloaded
    if os.path.exists(image_path):
        successful += 1
        continue

    try:
        # Request a medium-resolution image rather than a thumbnail
        medium_url = image_url.replace("square", "medium")

        response = session.get(medium_url, timeout=30)
        response.raise_for_status()

        # Open and convert image
        img = Image.open(BytesIO(response.content))
        img = img.convert("RGB")

        # Save image
        img.save(image_path, "JPEG", quality=95)

        successful += 1

    except Exception as e:
        failed.append({
            "observation_id": obs_id,
            "category": category,
            "url": image_url,
            "error": str(e)
        })

    if (index + 1) % 100 == 0:
        print(f"Processed {index + 1}/{len(df)} images")

print("\nDOWNLOAD COMPLETE")
print("Successful:", successful)
print("Failed:", len(failed))

